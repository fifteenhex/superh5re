#!/usr/bin/env python3
"""Generate cops.S and cops.h: the SHcompact routines of the test kit.

Convention (harness.h, cop_call): a routine receives a, b, c, d in R4-R7 and
returns R0-R3. Templates below put the instruction's destination in R0, the
T-bit in R1 (MOVT) and secondary state in R2/R3. Routines using a T-bit input
take it from bit 0 of d (SHLR R7). Delayed-branch routines carry their own
RTS; the others get "rts; nop" appended. Routines may use R0-R7, must keep
R8-R15 and PR (saved around BSR/JSR), and may change GBR, MACH/MACL and the
T-bit.
"""
import sys

R = []          # (name, body) in order

def add(name, body, own_rts=False):
    lines = [l.strip() for l in body.strip().split('\n') if l.strip()]
    if not own_rts:
        lines += ['rts', 'nop']
    R.append((name, lines))

def main():
    # routine tables: groups/<group>_cops.py, each with define(add)
    import glob, importlib.util
    for path in sorted(glob.glob('groups/*_cops.py')):
        spec = importlib.util.spec_from_file_location(path, path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        mod.define(add)
    with open('cops.S', 'w') as f:
        f.write('/* Generated by gen_cops.py: SHcompact test routines. Do not edit. */\n')
        f.write('\t.text\n\t.balign 4\n')
        for name, lines in R:
            f.write(f'\t.globl cop_{name}\n\t.type cop_{name}, @function\ncop_{name}:\n')
            for l in lines:
                f.write(f'\t{l}\n')
            f.write('\t.balign 4\n')
    with open('cops.h', 'w') as f:
        f.write('/* Generated by gen_cops.py. Do not edit. */\n')
        for name, _ in R:
            f.write(f'extern const u16 cop_{name}[];\n')
    print(f'{len(R)} routines')

if __name__ == '__main__':
    main()
